//  AI 模块拆分说明
//  原 ai.js 已拆分为以下独立模块（按依赖顺序）：
//
//  ai-utils.js   — 工具函数：JSON序列化、数据保存、确认弹窗、计时格式化
//  ai-conv.js    — 对话管理：设置弹窗、创建/切换/删除/清空对话、导出日志、标签页拖拽、输入草稿
//  ai-attach.js  — 附件处理：文件上传、预览、Kimi 文件处理、视觉文件识别
//  ai-render.js  — UI渲染：聊天界面、消息列表、Markdown/LaTeX 格式化
//  ai-tools.js   — 工具系统：工具定义、系统提示词构建、工具执行、调用解析
//  ai-search.js  — 网络搜索 & 通知：多引擎搜索、Windows 通知、侧边栏徽章
//  ai-api.js     — API通信：API 调用、消息构建、工具调用循环
//  ai-send.js    — 消息发送：发送流程、候选回复管理、工具栏、快速操作
//
