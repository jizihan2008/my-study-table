"""Build the offline CET decks from ECDICT (MIT); run only to refresh data."""
import csv
import gzip
import io
import json
from pathlib import Path
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
BASE = 'https://raw.githubusercontent.com/skywind3000/ECDICT/'
request = urllib.request.Request('https://api.github.com/repos/skywind3000/ECDICT/commits/master', headers={'User-Agent': 'My-Study-Table'})
revision = json.load(urllib.request.urlopen(request, timeout=60))['sha']
print('ECDICT revision: ' + revision, flush=True)
decks = {'cet4': [], 'cet6': []}
request = urllib.request.Request(BASE + revision + '/ecdict.csv', headers={'Accept-Encoding': 'gzip'})
with urllib.request.urlopen(request, timeout=120) as response:
    stream = gzip.GzipFile(fileobj=response) if response.headers.get('Content-Encoding') == 'gzip' else response
    for index, row in enumerate(csv.DictReader(io.TextIOWrapper(stream, encoding='utf-8-sig'))):
        if index and index % 100000 == 0:
            print('Scanned ' + str(index) + ' entries', flush=True)
        tags = row['tag'].split()
        if not row['word'].strip() or not row['translation'].strip():
            continue
        card = [row['word'], row['phonetic'], row['translation'].replace('\\n', '\n'), row['definition'].replace('\\n', '\n')]
        for level in decks:
            if level in tags:
                decks[level].append(card)
for level, cards in decks.items():
    unique = {card[0].lower(): card for card in cards}
    decks[level] = sorted(unique.values(), key=lambda card: card[0].lower())
destination = ROOT / 'lib' / 'cet'
destination.mkdir(parents=True, exist_ok=True)
(destination / 'vocabulary.js').write_text(
    '// Generated by scripts/build-cet-vocabulary.py; ECDICT, MIT license.\n'
    '// Source revision: ' + revision + '\n'
    '// Columns: word, phonetic, Chinese meaning, English definition.\n'
    'window.CetVocabulary = ' + json.dumps(decks, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
license_text = urllib.request.urlopen(BASE + revision + '/LICENSE', timeout=60).read().decode('utf-8')
(destination / 'LICENSE').write_text(license_text, encoding='utf-8')
(destination / 'README.md').write_text(
    '# 四六级离线词库\n\n来源：https://github.com/skywind3000/ECDICT\n\n'
    '版本：`' + revision + '`，MIT 许可见 LICENSE。\n\n'
    '按 cet4、cet6 标签分别提取，去重后保留音标、中英文释义；考试标签以来源为准，不声称覆盖最新官方大纲。\n\n'
    + '\n'.join(level + ': ' + str(len(cards)) + ' 词' for level, cards in decks.items())
    + '\n\n更新：`python scripts/build-cet-vocabulary.py`。词库不含用户进度。\n', encoding='utf-8')
print({level: len(cards) for level, cards in decks.items()})
